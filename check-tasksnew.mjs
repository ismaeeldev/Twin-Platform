import { chromium } from "playwright"
const browser = await chromium.launch()
const page = await browser.newPage()
page.on("pageerror", e => console.log("PAGEERROR:\n" + e.message))
page.on("console", msg => { if (msg.type() === "error") console.log("CONSOLE ERROR:", msg.text().slice(0, 500)) })
await page.goto("http://localhost:3000/signup", { timeout: 15000 })
await page.fill('#name', 'Hydration Test')
await page.fill('#email', 'hydrationtest@example.com')
await page.fill('#password', 'TestPassword123!')
await page.fill('#confirmPassword', 'TestPassword123!')
await page.click('button[type="submit"]')
await page.waitForURL(/\/onboarding/, { timeout: 15000 }).catch(()=>{})
await page.goto("http://localhost:3000/tasks/new", { timeout: 15000 })
await page.waitForTimeout(3000)
console.log("done checking")
await browser.close()
